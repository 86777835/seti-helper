// Passing (规 19). first: this is the first pass of the round.
export function passSteps(S, first) {
  const out = [{ t: '手牌超过 4 张的，弃到 4 张。轮中手牌没有上限，只在跳过时检查。', src: '规 19' }];
  if (first) {
    out.push({ t: `本轮<b>第一个跳过</b>的人：把一轮结束牌上的公转提醒标记拿开${S.round === LAST_ROUND ? '弃掉' : '放一旁'}，然后<b>转太阳系</b>（看科技版图上的公转计数标记转哪一层，转完计数标记前进一格）。${S.round === LAST_ROUND ? '第 5 轮也要转。' : ''}`, src: '规 19' });
    if (found(S, 'anomalies')) out.push({ t: '异常点：转完检查地球是否和某个异常点在同一扇区，是就立即结算这个异常点。', src: '种 4' });
  }
  if (S.round < LAST_ROUND) out.push({ t: '从本轮那叠一轮结束牌里选 1 张拿走，其余放回。最后一个跳过的人从剩下 2 张里选 1 张，另一张弃掉。', src: '规 19' });
  return out;
}

