// Between rounds (规 19; with organizations 扩 5).
export function betweenRounds(S) {
  if (S.round === LAST_ROUND) return [{ t: '第 5 轮结束，<b>不再拿收入</b>，直接终局计分。', src: '规 19 · BGG 3444223' }];
  const out = [
    S.org ? { t: '所有人拿收入：研究机构上印的收入，加上插在下面的所有牌右下角的资源。研究机构“每轮一次”的能力用过的，把标记拿下来。', src: '扩 5' }
      : { t: '所有人拿收入：起始收入牌正面（3 信用点、2 能量、1 张随机牌，牌从牌库顶摸），加上插在下面的所有牌右下角的资源。已跳过的人可以先拿。', src: '规 19' },
    { t: solo(S) ? '起始玩家标记交给另一方（你和对手轮流先手）。' : '起始玩家标记左移一位（顺时针下一位）。', src: solo(S) ? '规 22' : '规 19' },
    { t: '公转提醒标记移到下一轮的那叠一轮结束牌上。', src: '规 19' }
  ];
  if (solo(S) && S.solo.diff > 1) out.splice(1, 0, { t: `目标：拿收入之前，消耗 ${S.round} 个已完成的目标（第几轮就消耗几个），每少 1 个，对手进度前进 3 格。${S.org ? '长期目标上每个没完成的任务也让对手前进。' : ''}`, src: S.org ? '规 26 · 扩 7' : '规 26' });
  return out;
}

